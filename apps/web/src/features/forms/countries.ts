export interface FieldOptionDraft {
  id?: string;
  label: string;
  kind: 'option' | 'row' | 'column';
  imageUrl?: string | null;
  value?: string | null;
}

/**
 * Creates option items for all countries in the world, plus a custom "Other" option.
 */
export function createCountryFieldOptions(): FieldOptionDraft[] {
  const options: FieldOptionDraft[] = WORLD_COUNTRIES.map((country) => ({
    id: typeof crypto !== 'undefined' ? crypto.randomUUID() : undefined,
    label: country,
    kind: 'option',
    imageUrl: null,
    value: country,
  }));

  // Add the custom "Other" option at the end
  options.push({
    id: typeof crypto !== 'undefined' ? crypto.randomUUID() : undefined,
    label: 'Other (Please specify)',
    kind: 'option',
    imageUrl: null,
    value: 'Other',
  });

  return options;
}
